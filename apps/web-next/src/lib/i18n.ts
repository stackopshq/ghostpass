const messages: Record<Locale, Dict> = { en, fr };

function detect(): Locale {
  if (typeof window === "undefined") return "en";
  const stored = localStorage.getItem(STORAGE_KEY) as Locale | null;
  if (stored && messages[stored]) return stored;
  const nav = (navigator.language || "en").slice(0, 2) as Locale;
  return messages[nav] ? nav : "en";
}

// --- Réactivité, portée de Svelte à React ---------------------------------
//
// La rune `$state` de Svelte rendait la langue réactive depuis un module. React
// n'a pas d'équivalent hors composant : l'état vit dans un contexte, et les
// consommateurs s'y abonnent. Les dictionnaires ci-dessus, eux, n'ont pas
// changé d'une ligne — c'est la seule partie de ce fichier que le portage
// touche.
//
// `detect()` lit `localStorage` et `navigator`, qui n'existent pas au rendu
// serveur. Le fournisseur démarre donc en anglais et corrige APRÈS le montage :
// rendre côté serveur ce que seul le navigateur peut savoir produirait une
// discordance d'hydratation, et React remplacerait alors tout l'arbre.

import { createContext, useCallback, useContext, useEffect, useMemo, useState } from "react";

export function traduire(
  locale: Locale,
  key: string,
  params?: Record<string, string | number>,
): string {
  let s = messages[locale][key] ?? en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export interface I18n {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
}

const Ctx = createContext<I18n | null>(null);

export function useI18nValue(): I18n {
  const [locale, setLocaleState] = useState<Locale>("en");

  // Après le montage seulement : voir l'en-tête sur l'hydratation.
  useEffect(() => {
    const l = detect();
    setLocaleState(l);
    document.documentElement.lang = l;
  }, []);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    localStorage.setItem(STORAGE_KEY, l);
    // L'attribut `lang` du document suit la langue choisie : il pilote la
    // césure, la synthèse vocale et la correction orthographique. Le laisser
    // figé ferait lire une langue avec les règles d'une autre.
    document.documentElement.lang = l;
  }, []);

  const t = useCallback(
    (key: string, params?: Record<string, string | number>) => traduire(locale, key, params),
    [locale],
  );

  return useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);
}

export const I18nContext = Ctx;

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error("useI18n hors de son fournisseur");
  return v;
}
